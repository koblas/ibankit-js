/** Give an IBAN correct mod-97 check digits, so only its BBAN structure decides validity. */
function withCheckDigits(iban: string): string {
  return replaceCheckDigit(iban, calculateCheckDigit(iban));
}

describe("SWIFT IBAN Registry", () => {
  it.each(REGISTRY_EXAMPLES)("accepts the registry example %s", (example) => {
    expect(IBAN.isValid(example)).toBe(true);
  });

  describe("BBAN character types follow the registry", () => {
    it.each([
      ["AE", "AE00033A234567890123456", "account number is 16!n"],
      ["PK", "PK00SCB10000001123456702", "bank code is 4!a"],
      ["TN", "TN0010006A35183598478831", "account number is 13!n"],
      ["TN", "TN001000603518359847883A", "national check digits are 2!n"],
      ["TR", "TR0000061A0519786457841326", "reserved digit is 1!n"],
      ["VA", "VA0000A123000012345678", "bank code is 3!n"],
      ["YE", "YE00CBY10001018861234567891234", "bank code is 4!a"],
      ["YE", "YE00CBYE000A018861234567891234", "branch code is 4!n"],
    ])("%s rejects %s: %s", (_cc, iban) => {
      expect(IBAN.isValid(withCheckDigits(iban))).toBe(false);
    });

    it.each([
      ["BR", "BR0099999AB3000010009795493C1", "bank code is 8!c (since Aug 2026)"],
      ["BR", "BR0000360305000010009795493P1", "a numeric bank code is still valid"],
      ["BR", "BR00003603050000100097954931A", "account type is 1!c"],
      ["GT", "GT00TRAJAB020000001210029690", "positions 5-8 are 20!c, not numeric"],
      ["LC", "LC00HEMM000100010012001200023A15", "account number is 24!c"],
      ["UA", "UA003223130000026007233566A01", "account number is 19!c"],
    ])("%s accepts %s: %s", (_cc, iban) => {
      expect(IBAN.isValid(withCheckDigits(iban))).toBe(true);
    });
  });

  describe("YE (added to the registry Jul 2024)", () => {
    it("extracts bank, branch and account number", () => {
      const iban = new IBAN("YE15CBYE0001018861234567891234");
      expect(iban.getBankCode()).toBe("CBYE");
      expect(iban.getBranchCode()).toBe("0001");
      expect(iban.getAccountNumber()).toBe("018861234567891234");
    });
  });
});
